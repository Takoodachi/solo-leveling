// The Android app's icon in each theme's colours (src/features/settings/appIcon.ts picks one).
// For every theme: a vector foreground (the Ascent mark: top chevron in the accent, the others in
// the theme's text colour) on its background colour, as an adaptive icon, and a launcher entry
// (an activity-alias of MainActivity, one switched on at a time) in AndroidManifest.xml, between
// the "Theme icons" markers. Run: node scripts/generate-theme-icons.mjs
//
// The colours are each theme's background, primary and foreground as the app resolves them.
// After changing a theme, refresh THEMES from the browser console on the dev server:
//   const { THEMES } = await import('/src/features/settings/themes.ts')  (then hsl → hex)
import { readFile, writeFile, mkdir } from 'fs/promises'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const THEMES = [
  { id: 'ember', bg: '#0a0a0b', accent: '#ff5e1a', fg: '#fafafa' },
  { id: 'monarch', bg: '#0b0811', accent: '#9955f1', fg: '#f6f5fa' },
  { id: 'abyss', bg: '#060a13', accent: '#06d0f9', fg: '#f4f7fa' },
  { id: 'verdant', bg: '#070e0b', accent: '#1dc973', fg: '#f3f7f4' },
  { id: 'bloodmoon', bg: '#0d0809', accent: '#f23649', fg: '#f8f7f7' },
  { id: 'gold', bg: '#0d0b07', accent: '#f9c11a', fg: '#faf8f5' },
  { id: 'neon', bg: '#0f0812', accent: '#f745b6', fg: '#f8f5fa' },
  { id: 'graphite', bg: '#0e0f11', accent: '#4a8cf7', fg: '#f7f7f8' },
  { id: 'volt', bg: '#0a0d08', accent: '#a0ed1d', fg: '#f7f9f5' },
  { id: 'daylight', bg: '#f7f5f2', accent: '#ff4c00', fg: '#121216' },
  { id: 'glacier', bg: '#f1f5f9', accent: '#0d70f2', fg: '#0e1525' },
  { id: 'matcha', bg: '#f1f5f0', accent: '#0b8e5e', fg: '#101e17' },
  { id: 'sakura', bg: '#fcf3f6', accent: '#e31c6c', fg: '#26171c' },
  { id: 'iris', bg: '#f5f4fb', accent: '#783be3', fg: '#181528' },
  { id: 'lagoon', bg: '#eef6f7', accent: '#088491', fg: '#112122' },
  { id: 'honey', bg: '#f9f6eb', accent: '#c77905', fg: '#241f0f' },
  { id: 'cherry', bg: '#f9f2f1', accent: '#d71d30', fg: '#24130f' },
  { id: 'paper', bg: '#f4f3f1', accent: '#303036', fg: '#1d1b16' },
]
/** The one switched on in a fresh install (the default theme). */
const DEFAULT = 'ember'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const res = join(root, 'android', 'app', 'src', 'main', 'res')
const manifestPath = join(root, 'android', 'app', 'src', 'main', 'AndroidManifest.xml')
// Must match iconAlias() in src/features/settings/appIcon.ts
const alias = id => `Icon${id[0].toUpperCase()}${id.slice(1)}`
const chevron = y => `M50,${y} L80,${y + 30} L67,${y + 30} L50,${y + 13} L33,${y + 30} L20,${y + 30} Z`

await mkdir(join(res, 'drawable'), { recursive: true })
await mkdir(join(res, 'mipmap-anydpi-v26'), { recursive: true })

for (const t of THEMES) {
  // Same geometry as the PNG foreground in generate-icons.mjs: the 100-unit mark at 0.56, centred on 108 dp
  await writeFile(join(res, 'drawable', `ic_launcher_fg_${t.id}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-theme-icons.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="100" android:viewportHeight="100">
    <group android:pivotX="50" android:pivotY="48" android:scaleX="0.56" android:scaleY="0.56" android:translateY="2">
        <path android:fillColor="${t.accent}" android:pathData="${chevron(12)}" />
        <path android:fillColor="${t.fg}" android:pathData="${chevron(33)} ${chevron(54)}" />
    </group>
</vector>
`)
  await writeFile(join(res, 'mipmap-anydpi-v26', `ic_launcher_${t.id}.xml`), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-theme-icons.mjs -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_bg_${t.id}" />
    <foreground android:drawable="@drawable/ic_launcher_fg_${t.id}" />
</adaptive-icon>
`)
}

await writeFile(join(res, 'values', 'theme_icons.xml'), `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-theme-icons.mjs -->
<resources>
${THEMES.map(t => `    <color name="ic_launcher_bg_${t.id}">${t.bg}</color>`).join('\n')}
</resources>
`)

const aliases = THEMES.map(t => `        <activity-alias
            android:name=".${alias(t.id)}"
            android:targetActivity=".MainActivity"
            android:icon="@mipmap/ic_launcher_${t.id}"
            android:roundIcon="@mipmap/ic_launcher_${t.id}"
            android:label="@string/title_activity_main"
            android:enabled="${t.id === DEFAULT}"
            android:exported="true">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>`).join('\n')

const START = '<!-- Theme icons (scripts/generate-theme-icons.mjs) -->'
const END = '<!-- /Theme icons -->'
const manifest = await readFile(manifestPath, 'utf8')
const from = manifest.indexOf(START)
const to = manifest.indexOf(END)
if (from < 0 || to < from) throw new Error(`AndroidManifest.xml needs the markers ${START} and ${END}`)
const nl = manifest.includes('\r\n') ? '\r\n' : '\n'
await writeFile(manifestPath, manifest.slice(0, from + START.length) + nl + aliases.replace(/\n/g, nl) + nl + '        ' + manifest.slice(to))
console.log(`Generated ${THEMES.length} theme icons and their launcher entries`)
